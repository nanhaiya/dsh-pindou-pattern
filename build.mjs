/**
 * Build client.js from the hand-written sources.
 *
 *   src/palette.json  291 MARD colors
 *   src/engine.js     pure palette / sampling / quantization logic
 *   src/shared.js     shared i18n / CSS / canvas rendering helpers
 *   src/ui.js         React + DOM browser half
 *
 * The engine starts with `const MARD = __MARD__;`; the placeholder is replaced
 * with the palette data so the bundle ships a single self-contained script.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)));
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const palette = JSON.parse(readFileSync(join(root, 'src', 'palette.json'), 'utf8'));
let engine = readFileSync(join(root, 'src', 'engine.js'), 'utf8');
const shared = readFileSync(join(root, 'src', 'shared.js'), 'utf8');
const ui = readFileSync(join(root, 'src', 'ui.js'), 'utf8');

if (!engine.includes('const MARD = __MARD__;')) {
  throw new Error('src/engine.js: MARD placeholder is missing');
}
if (!/function apply\s*\(ctx\)/.test(ui)) {
  throw new Error('src/ui.js: apply(ctx) is missing');
}
if (!engine.includes('function buildPattern') || !engine.includes('function sampleGrid')) {
  throw new Error('src/engine.js: engine functions are missing');
}

engine = engine.replace('const MARD = __MARD__;', 'const MARD = ' + JSON.stringify(palette) + ';');

const bundle = [
  '/* dsh-pindou-pattern — generated by build.mjs; edit src/engine.js or src/ui.js instead. */',
  'window.__ModuleLoader__.load({',
  '  id: ' + JSON.stringify(pkg.name) + ',',
  '  factory(require) {',
  '    const React = require("react");',
  engine.trim(),
  shared.trim(),
  ui.trim(),
  '    return {',
  '      name: ' + JSON.stringify(pkg.name) + ',',
  '      inject: ["slots", "locale"],',
  '      apply,',
  '    };',
  '  },',
  '});',
  '',
].join('\n');

writeFileSync(join(root, 'client.js'), bundle);
console.log('client.js written: ' + (Buffer.byteLength(bundle) / 1024).toFixed(1) + ' KiB, palette ' + palette.length + ' colors');
